/**
 * Export the migrations and dev seed (single source: src/store/migrations.ts, src/store/seed.ts)
 * to standalone SQL for psql-only environments:
 *   db/migrations/NNNN_<name>.sql   one file per migration (reference / review)
 *   db/psql/migrate.psql            ordered, idempotent runner with ledger, checksums, lock
 *   db/seed/dev-seed.sql            guarded dev seed
 * `pnpm db:export` writes; `pnpm db:export --check` fails if the committed files are stale.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { LEDGER_DDL, MIGRATIONS, MIGRATION_LOCK_KEY, checksumOf } from "../src/store/migrations.js";
import { DEV_SEED_SQL } from "../src/store/seed.js";

const root = new URL("..", import.meta.url).pathname;
const header = "-- GENERATED by `pnpm db:export` from src/store. Do not edit; add a new migration in src/store/migrations.ts.\n";
const files = new Map<string, string>();
const latest = MIGRATIONS.length;

for (const m of MIGRATIONS) {
  files.set(`db/migrations/${String(m.version).padStart(4, "0")}_${m.name}.sql`, `${header}-- version ${m.version} (${m.name}) sha256 ${checksumOf(m.sql)}\n${m.sql}`);
}

const ps: string[] = [
  header.trimEnd(),
  "-- Usage: psql \"$DATABASE_MIGRATION_URL\" -X -v ON_ERROR_STOP=1 -f db/psql/migrate.psql",
  "-- Same ledger, checksums, and advisory lock as `pnpm db:migrate`; safe to run repeatedly.",
  "\\set ON_ERROR_STOP on",
  "SET client_min_messages = warning;",
  "BEGIN;",
  `SELECT pg_advisory_xact_lock(${MIGRATION_LOCK_KEY});`,
  LEDGER_DDL,
  `DO $chk$ BEGIN IF EXISTS (SELECT 1 FROM schema_migrations WHERE version > ${latest}) THEN RAISE EXCEPTION 'database has migrations newer than these files (latest ${latest}); never downgrade'; END IF; END $chk$;`,
  "COMMIT;",
];
for (const m of MIGRATIONS) {
  const sum = checksumOf(m.sql);
  ps.push(
    "",
    `-- ---- ${m.version} ${m.name}`,
    "BEGIN;",
    `SELECT pg_advisory_xact_lock(${MIGRATION_LOCK_KEY});`,
    `DO $chk$ BEGIN IF EXISTS (SELECT 1 FROM schema_migrations WHERE version = ${m.version} AND checksum IS NOT NULL AND checksum <> '${sum}') THEN RAISE EXCEPTION 'migration ${m.version} (${m.name}) checksum drift: restore the original SQL and add a new forward migration'; END IF; END $chk$;`,
    `UPDATE schema_migrations SET checksum = '${sum}' WHERE version = ${m.version} AND checksum IS NULL;`,
    `SELECT EXISTS (SELECT 1 FROM schema_migrations WHERE version = ${m.version}) AS wd_done \\gset`,
    "\\if :wd_done",
    `\\echo 'migration ${m.version} ${m.name}: already applied'`,
    "\\else",
    m.sql.trim(),
    `INSERT INTO schema_migrations (version, name, checksum) VALUES (${m.version}, '${m.name}', '${sum}');`,
    `\\echo 'migration ${m.version} ${m.name}: applied'`,
    "\\endif",
    "COMMIT;",
  );
}
ps.push("", "SELECT version, name, left(checksum, 12) AS checksum, applied_at FROM schema_migrations ORDER BY version;", "");
files.set("db/psql/migrate.psql", ps.join("\n"));
files.set("db/seed/dev-seed.sql", `${header}-- Usage: psql "$DATABASE_MIGRATION_URL" -X -v ON_ERROR_STOP=1 -1 -f db/seed/dev-seed.sql\n${DEV_SEED_SQL}`);

const check = process.argv.includes("--check");
const stale: string[] = [];
for (const [rel, body] of files) {
  const abs = join(root, rel);
  if (check) {
    if (!existsSync(abs) || readFileSync(abs, "utf8") !== body) stale.push(rel);
  } else {
    mkdirSync(join(abs, ".."), { recursive: true });
    writeFileSync(abs, body);
  }
}
const extra = existsSync(join(root, "db/migrations")) ? readdirSync(join(root, "db/migrations")).map((f) => `db/migrations/${f}`).filter((f) => !files.has(f)) : [];
if (check) {
  if (stale.length || extra.length) {
    console.error(`SQL exports are stale: ${[...stale, ...extra].join(", ")}. Run: pnpm db:export`);
    process.exit(1);
  }
  console.log(`SQL exports up to date (${files.size} files, latest migration ${latest})`);
} else console.log(`wrote ${files.size} files (latest migration ${latest})`);
